-- V2.15 precision pass: suppress high-confidence noise before it consumes validation time.
-- Adds P1/P2/P3 research priority without treating priority as proof of demand.

alter table public.research_leads
  add column if not exists research_priority text not null default 'p3',
  add column if not exists priority_reason text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid='public.research_leads'::regclass
      and conname='research_leads_priority_check'
  ) then
    alter table public.research_leads
      add constraint research_leads_priority_check
      check (research_priority in ('p1','p2','p3'));
  end if;
end $$;

create index if not exists research_leads_priority_status_recent
  on public.research_leads(research_priority,status,created_at desc);

create or replace function public.radar_github_internal_issue(
  p_title text,
  p_body text,
  p_payload jsonb
)
returns boolean
language sql
immutable
set search_path=pg_catalog
as $$
  select
    lower(coalesce(p_payload->'user'->>'type',''))='bot'
    or lower(coalesce(p_body,'')) ~
      '(this was generated by ai during triage|generated from document-first|unit of work for one agent|dispatched to a subagent)'
    or (
      lower(coalesce(p_payload->>'author_association','')) in ('owner','member','collaborator')
      and (
        lower(coalesce(p_title,'')) ~
          '^(task:|ops-[0-9]+:|uc-[0-9]+:|\[devops\]|platform spike:|design:|[0-9]{4}-[0-9]{2}-[0-9]{2}[ ]*\|)'
        or lower(coalesce(p_body,'')) ~
          '(lane owns|must not touch|done when|planning document:|one discovery artifact:|parent issue:[ ]*#[0-9]+|subtask of #[0-9]+|blocked by #[0-9]+|definition of done for this issue|current checkpoint:|implementation repository:|status[ ]*\*\*proposed, not decided|nothing here should be implemented|owner has to choose between the options|bug-fixing sweep|found while fixing #[0-9]+|no mainstream client triggers|exploratory business roles and revenue models only|not a launch recommendation|not a .*validation plan|customer outreach.*not)'
        or exists (
          select 1
          from jsonb_array_elements(coalesce(p_payload->'labels','[]'::jsonb)) label
          where lower(coalesce(label->>'name','')) ~
            '(type:task|owner:agent|ready-for-agent|stage:(plan-approved|needs-spec)|^architecture$|(^|:)chore$|^internal$)'
        )
      )
    );
$$;

create or replace function public.radar_freelancer_low_value_task(
  p_title text,
  p_body text,
  p_payload jsonb
)
returns boolean
language sql
immutable
set search_path=pg_catalog
as $$
  with x as (
    select lower(concat_ws(' ',coalesce(p_title,''),coalesce(p_body,''))) txt,
           lower(coalesce(p_title,'')) title,
           length(coalesce(p_body,'')) body_len
  )
  select
    txt ~ '(data entry|copy typing|copy-typing|straightforward text data entry|manual transcription|typing job|pdf text extraction|extract(ing)? the text exactly|converted? into clean,? (error-free )?text)'
    or title ~ '(discord welcome bot|windows-based game automation)'
    or (
      body_len < 500
      and title ~ '(specialist|expert)'
      and txt ~ '(automation|crm|oracle|n8n|gohighlevel)'
    )
  from x;
$$;

create or replace function public.radar_stackoverflow_product_intent(
  p_title text,
  p_body text
)
returns boolean
language sql
immutable
set search_path=pg_catalog
as $$
  select lower(concat_ws(' ',coalesce(p_title,''),coalesce(p_body,''))) ~
    '(would pay|willing to pay|paid (tool|app|service)|pay for (a|an|this) (tool|app|service)|looking for (a|an|some) (paid )?(tool|app|service|alternative)|need (a|an) (commercial|hosted|paid) (tool|app|service)|subscription.{0,40}(looking|need|replace))';
$$;

