create or replace function public.radar_precision_guard_signal()
returns trigger
language plpgsql
security invoker
set search_path=public,pg_catalog
as $$
declare
  r record;
begin
  select ri.title,ri.body,ri.raw_payload,src.key as source_key
    into r
  from public.raw_items ri
  join public.sources src on src.id=ri.source_id
  where ri.id=new.raw_item_id;

  if r.source_key='github'
     and public.radar_github_internal_issue(r.title,r.body,r.raw_payload) then
    new.is_actionable:=false;
    new.evidence_role:='market_context';
    new.money_signal_type:='none';
    new.purchase_intent_score:=least(coalesce(new.purchase_intent_score,1),1);
    if position('+v215-internal-guard' in coalesce(new.extraction_version,''))=0 then
      new.extraction_version:=left(coalesce(new.extraction_version,'') || '+v215-internal-guard',120);
    end if;
  elsif r.source_key='freelancer'
     and public.radar_freelancer_low_value_task(r.title,r.body,r.raw_payload) then
    new.is_actionable:=false;
    if position('+v215-labor-guard' in coalesce(new.extraction_version,''))=0 then
      new.extraction_version:=left(coalesce(new.extraction_version,'') || '+v215-labor-guard',120);
    end if;
  elsif r.source_key='stackoverflow'
     and not public.radar_stackoverflow_product_intent(r.title,r.body) then
    new.is_actionable:=false;
    new.evidence_role:='market_context';
    new.money_signal_type:='none';
    new.purchase_intent_score:=least(coalesce(new.purchase_intent_score,1),1);
    if position('+v215-so-intent-guard' in coalesce(new.extraction_version,''))=0 then
      new.extraction_version:=left(coalesce(new.extraction_version,'') || '+v215-so-intent-guard',120);
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_radar_precision_guard_signal on public.signals;
create trigger trg_radar_precision_guard_signal
before insert or update of is_actionable,evidence_role,money_signal_type,purchase_intent_score
on public.signals
for each row execute function public.radar_precision_guard_signal();

create or replace function public.radar_research_priority_for_signal(p_signal_id uuid)
returns text
language sql
stable
security invoker
set search_path=public,pg_catalog
as $$
  with x as (
    select s.*,src.key source_key,ri.title,ri.body,ri.raw_payload,
           lower(concat_ws(' ',coalesce(ri.title,''),coalesce(ri.body,''),coalesce(s.problem,''))) txt
    from public.signals s
    join public.raw_items ri on ri.id=s.raw_item_id
    join public.sources src on src.id=s.source_id
    where s.id=p_signal_id
  )
  select case
    when not coalesce(is_actionable,false) then 'p3'

    when source_key='hackernews'
      and lower(coalesce(title,'')) ~
        '^(what tools do you wish existed|tell hn: looking for help|get feedback|ask hn: what are you building)'
      then 'p3'
    when source_key='hackernews'
      and (
        money_signal_type='purchase_request'
        or (
          coalesce(pain_score,0)>=7
          and coalesce(evidence_quality_score,0)>=8
          and txt ~ '(daily|weekly|monthly|hours|minutes|every time|each time|manual|manually|blocked|cost|pay|budget|[0-9]+[ ,]?(users|teams|clients|requests|tokens|hours))'
        )
      ) then 'p1'
    when source_key='hackernews' and evidence_role='problem_demand'
      and coalesce(pain_score,0)>=5 and coalesce(evidence_quality_score,0)>=6
      then 'p2'

    when source_key='amo_reviews' and evidence_role='problem_demand'
      and coalesce(pain_score,0)>=7 then 'p1'
    when source_key='amo_reviews' and evidence_role='problem_demand'
      and coalesce(pain_score,0)>=5 then 'p2'

    when source_key='freelancer'
      and public.radar_freelancer_low_value_task(title,body,raw_payload)
      then 'p3'
    when source_key='freelancer'
      and (
        lower(coalesce(title,'')) ~
          '(lead generation|roofing|crm .*build|crm setup|specialist|expert|development|game automation|discord .*bot|bookkeeping with custom reports)'
        or (
          txt ~ '(looking for|seeking|commissioning|i need|i want).{0,100}(developer|develop|create|build|application|app|platform|crm|bot|tool|mvp)'
          and txt !~ '(remind|follow.?up|supplier|vendor|product feed|supplier feed|any file that follows the same column structure|rule-driven|monthly close|reconcil|missing (documents?|items?|information))'
        )
      ) then 'p3'
    when source_key='freelancer'
      and coalesce(raw_payload->>'demand_class','')='repeatable_workflow'
      and txt ~ '(scheduled|remind|follow.?up|recurring|repeatable|batch|reconcil|supplier|vendor|product feed|supplier feed|outstanding|missing (documents?|items?|information)|any file that follows the same column structure|rule-driven|[0-9][0-9,]* (skus?|messages?|records?|rows?|clients?|vendors?|invoices?))'
      and txt !~ '(lead generation|roofing leads|game automation)'
      then 'p2'
    else 'p3'
  end
  from x;
$$;

-- Backfill priorities while preserving human promotion decisions.
update public.research_leads rl
set research_priority=case
      when rl.status='validate' then 'p1'
      when rl.status='research' then
        case when public.radar_research_priority_for_signal(rl.anchor_signal_id)='p3' then 'p2'
             else public.radar_research_priority_for_signal(rl.anchor_signal_id) end
      else public.radar_research_priority_for_signal(rl.anchor_signal_id)
    end,
    priority_reason=case
      when rl.status='validate' then 'Manual validation track: keep at the top until Build or Archive.'
      when rl.status='research' then 'Manually promoted to Research; worth active review but not validated demand.'
      when public.radar_research_priority_for_signal(rl.anchor_signal_id)='p1'
        then 'Strong explicit/quantified problem signal; review first.'
      when public.radar_research_priority_for_signal(rl.anchor_signal_id)='p2'
        then 'Specific product-shaped workflow worth manual review.'
      else 'Single, vague, generic-labor or custom-build signal; keep out of the active inbox.'
    end,
    updated_at=now();

update public.research_leads
set status='archived',
    decision_reason=coalesce(
      nullif(decision_reason,''),
      'V2.15 auto-triage: low-priority single/custom-service signal; no active validation slot.'
    ),
    priority_reason='Single, vague, generic-labor or custom-build signal; keep out of the active inbox.',
    reviewed_at=coalesce(reviewed_at,now()),
    updated_at=now()
where origin='auto' and status='new' and research_priority='p3';

create or replace function public.radar_research_lead_priority_guard()
returns trigger
language plpgsql
security invoker
set search_path=public,pg_catalog
as $$
declare
  v_priority text;
begin
  if new.status='validate' then
    v_priority:='p1';
    new.priority_reason:='Manual validation track: keep at the top until Build or Archive.';
  elsif new.status='research' then
    v_priority:=public.radar_research_priority_for_signal(new.anchor_signal_id);
    if v_priority='p3' then v_priority:='p2'; end if;
    new.priority_reason:='Manually promoted to Research; worth active review but not validated demand.';
  elsif new.origin='curated' and new.status<>'archived' then
    v_priority:='p2';
    new.priority_reason:='Manually curated source-backed lead.';
  else
    v_priority:=public.radar_research_priority_for_signal(new.anchor_signal_id);
    new.priority_reason:=case v_priority
      when 'p1' then 'Strong explicit/quantified problem signal; review first.'
      when 'p2' then 'Specific product-shaped workflow worth manual review.'
      else 'Single, vague, generic-labor or custom-build signal; keep out of the active inbox.'
    end;
  end if;

  new.research_priority:=v_priority;

  if new.origin='auto' and new.status='new' and v_priority='p3' then
    new.status:='archived';
    new.decision_reason:=coalesce(
      nullif(new.decision_reason,''),
      'V2.15 auto-triage: low-priority single/custom-service signal; no active validation slot.'
    );
    new.reviewed_at:=coalesce(new.reviewed_at,now());
  end if;

  return new;
end;
$$;

drop trigger if exists trg_research_lead_priority_guard on public.research_leads;
create trigger trg_research_lead_priority_guard
before insert or update of status,anchor_signal_id,origin
on public.research_leads
for each row execute function public.radar_research_lead_priority_guard();

